package wizard

import (
	"context"
	"errors"
	log "log/slog"
	"strings"

	tgbotapi "github.com/OvyFlash/telegram-bot-api"
	"github.com/kozalosev/goSadTgBot/base"
	"github.com/kozalosev/goSadTgBot/logconst"
)

const (
	// CallbackDataFieldPrefix is used in routing of callback updates.
	CallbackDataFieldPrefix = "field" + callbackDataSep

	callbackDataSep     = ":"
	callbackDataErrorTr = "callbacks.error"
)

var (
	callbackLogger = logconst.NewLoggerForHandler("wizard.CallbackQueryHandler")

	errFieldNotFound       = errors.New("field is not found in the form")
	errFormOfAnotherChat   = errors.New("the form is filled in another chat")
	errInvalidCallbackData = errors.New("CallbackQuery data has an unexpected number of fields")
	errNoMessageToContinue = errors.New("the message with the button or the message it replies to is inaccessible")
)

// CallbackQueryHandler is a handler for callback updates generated by messages for fields with inline buttons.
func CallbackQueryHandler(reqenv *base.RequestEnv, query *tgbotapi.CallbackQuery, resources *Env) {
	id := query.From.ID
	var (
		form       Form
		err        error
		fieldValue string
		logArgs    []any
	)
	// the message with the button is edited, and the form continues with the message it replies to
	if query.Message == nil || query.Message.ReplyToMessage == nil {
		err = errNoMessageToContinue
	} else if err = resources.stateStorage.GetCurrentState(id, &form); err == nil {
		if !form.BelongsTo(query.Message.Chat.ID) {
			err = errFormOfAnotherChat
		} else {
			data := strings.TrimPrefix(query.Data, CallbackDataFieldPrefix)
			dataArr := strings.Split(data, callbackDataSep)
			dataArrLen := len(dataArr)
			if dataArrLen == 2 {
				fieldName := dataArr[0]
				fieldValue = dataArr[1]
				if field := form.Fields.FindField(fieldName); field != nil {
					field.Data = Txt{Value: fieldValue}
					err = resources.stateStorage.SaveState(id, &form)
				} else {
					err = errFieldNotFound
					logArgs = append(logArgs, logconst.FieldName, fieldName)
				}
			} else {
				err = errInvalidCallbackData
				logArgs = append(logArgs, logconst.FieldValue, query.Data)
			}
		}
	}
	var c tgbotapi.Chattable
	if err != nil {
		level := log.LevelWarn
		if errors.Is(err, errFormOfAnotherChat) {
			level = log.LevelInfo // the user has pressed an old button in another chat: nothing is broken
		}
		callbackLogger.Use().Log(context.Background(), level, "Failed to process the callback query",
			append(logArgs, logconst.FieldError, err)...)
		c = tgbotapi.NewCallbackWithAlert(query.ID, reqenv.Lang.Tr(callbackDataErrorTr))
	} else {
		chosenValue := reqenv.Lang.Tr(fieldValue)
		c = tgbotapi.NewEditMessageText(query.Message.Chat.ID, query.Message.MessageID, query.Message.Text+" "+chosenValue)

		msg := query.Message.ReplyToMessage
		form.PopulateRestored(msg, resources)
		form.ProcessNextField(reqenv, msg)
	}
	if err := resources.appEnv.Bot.Request(c); err != nil {
		callbackLogger.LogFailedTelegramApiRequest(err)
	}
}
